// ─── PROMPT BUILDER ──────────────────────────────────────────────────────────

function buildSystem(scenarioId, difficulty, productFacts, managerTurns = 0, diff = DIFF_MODS.medium) {
  const p = CLIENT_PERSONAS[scenarioId] || CLIENT_PERSONAS.cold;

  let phaseNote;
  if (managerTurns <= 1) {
    phaseNote = `Начало разговора. Пишешь осторожно, задаёшь первые вопросы, проверяешь менеджера.`;
  } else if (managerTurns <= 3) {
    phaseNote = `Уже немного освоился. Если менеджер отвечал конкретно — стал чуть открытее. Двигаешься к следующим важным вопросам.`;
  } else {
    phaseNote = `У тебя уже сложилось мнение о менеджере. Либо движешься к решению, либо теряешь интерес.`;
  }

  const canEnd = managerTurns >= diff.min;
  const endRule = canEnd
    ? `Если разговор логично завершился и ты принял решение — напиши финальную реплику и добавь в самый конец: [РЕЗУЛЬТАТ: успех] или [РЕЗУЛЬТАТ: неудача]. Только один раз.`
    : `Рано заканчивать: ${managerTurns} из минимум ${diff.min} реплик. Не добавляй [РЕЗУЛЬТАТ:]. Продолжай диалог.`;

  return `Ты — реальный клиент в обучающем чате по продажам Qazaq Grill.
Переписка идёт в текстовом чате — пиши как человек пишет сообщения, не как говорит.

━━━ КТО ТЫ ━━━
${p.context}

━━━ ТВОЯ МОТИВАЦИЯ И СТРАХИ ━━━
${p.motivation}

━━━ ЧТО ТЕБЯ УБЕЖДАЕТ ━━━
${p.positive_triggers}

━━━ КАК ТЫ ПИШЕШЬ ━━━
${p.writing_style}

━━━ ТВОИ КОНКРЕТНЫЕ ВОПРОСЫ И ВОЗРАЖЕНИЯ ━━━
${p.objections}

━━━ ЧТО ТЕБЯ ОТТАЛКИВАЕТ ━━━
${p.losing_interest}

━━━ СЛОЖНОСТЬ: ${diff.label} ━━━
${diff.behavior}

━━━ ПРОДУКТЫ И ЦЕНЫ (реальные данные Qazaq Grill) ━━━
${productFacts}

━━━ ТЕКУЩИЙ МОМЕНТ (сообщение ${managerTurns}) ━━━
${phaseNote}

━━━ КАК РЕАГИРОВАТЬ НА МЕНЕДЖЕРА ━━━
Реагируй именно на конкретные слова менеджера — не отвечай в вакууме.
Если менеджер дал размытый ответ — не принимай его, напиши что хочешь конкретнее.
Если менеджер дал точный ответ с фактами — признай это и задай следующий вопрос.
Если менеджер не спросил детали твоей ситуации — это замечаешь и пишешь холоднее.
Если менеджер давит или торопит — становишься короче и сдержаннее в ответах.

━━━ ФОРМАТ СООБЩЕНИЙ ━━━
Это текстовый чат, не звонок. Пиши законченными предложениями.
1-4 предложения на сообщение. Можно 2 вопроса если они связаны.
Не используй разговорные обрывки ("ну...", "хм...") — это чат, пиши полноценно.
Только русский язык. Никогда не выходи из роли.

━━━ ЗАВЕРШЕНИЕ ━━━
${endRule}`;
}

// ─── HANDLER ─────────────────────────────────────────────────────────────────

export default async function handler(req, res) {
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const { messages, scenarioId, difficulty, productFacts } = req.body;

  if (!messages || !Array.isArray(messages)) {
    return res.status(400).json({ error: 'messages array is required' });
  }
  if (!scenarioId) {
    return res.status(400).json({ error: 'scenarioId is required' });
  }

  try {
    const diff = DIFF_MODS[difficulty] || DIFF_MODS.medium;
    const managerTurns = Math.max(0, messages.filter(m => m.role === 'user').length - 1);
    const system = buildSystem(scenarioId, difficulty || 'medium', productFacts || '', managerTurns, diff);
    const text = await openai({ system, messages, maxTokens: 300, temperature: 1.0 });
    return res.status(200).json({ text });
  } catch (err) {
    return res.status(500).json({ error: err.message });
  }
}
